#!/usr/bin/env python3
"""Build a single self-contained HTML file (images, icons, logo and font embedded as data URIs).

Usage:  python3 boutique-smiles/build_standalone.py
Output: boutique-smiles/teeth-cleaning-plantation-standalone.html
"""
import base64, io, mimetypes, os, re, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "teeth-cleaning-plantation.html")
OUT = os.path.join(HERE, "teeth-cleaning-plantation-standalone.html")

# max width per image (keeps the standalone file reasonably small)
MAX_W = {
    "img-holistic-dentist-banner.webp": 1600,
    "img-holistic-dentist-banner-mobile.webp": 750,
    "img-about-banner.webp": 1100,
    "img-section-bg.webp": 1100,
    "img-slider-1.webp": 900, "img-about-slider-1.webp": 900, "img-about-slider-2.webp": 900,
    "img-about-slider-4.webp": 900, "img-about-slider-5.webp": 900,
    "happy-patients-with-dentist-plantation.webp": 900,
    "smiling-patients-with-plantation-dentist.webp": 400,
}
DOCTOR_W = 640
ICON_W = 320

def encode(path):
    name = os.path.basename(path)
    ext = name.rsplit(".", 1)[-1].lower()
    data = open(path, "rb").read()
    mime = {"svg": "image/svg+xml", "woff2": "font/woff2", "webp": "image/webp",
            "jpg": "image/jpeg", "jpeg": "image/jpeg", "png": "image/png"}.get(ext) or mimetypes.guess_type(path)[0]
    if ext in ("webp", "jpg", "jpeg") :
        im = Image.open(io.BytesIO(data)).convert("RGB")
        if name in MAX_W: w = MAX_W[name]
        elif "dr-" in name.lower() or "gabi" in name or "giorgio" in name: w = DOCTOR_W
        elif im.width <= 700: w = ICON_W
        else: w = 1000
        if im.width > w:
            im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
        buf = io.BytesIO(); im.save(buf, "WEBP", quality=78, method=6); data = buf.getvalue(); mime = "image/webp"
    return f"data:{mime};base64," + base64.b64encode(data).decode("ascii"), len(data)

html = open(SRC, encoding="utf-8").read()
total = 0
def repl(m):
    global total
    rel = m.group(2)
    path = os.path.join(HERE, rel)
    if not os.path.exists(path):
        print("missing", rel, file=sys.stderr); return m.group(0)
    uri, n = encode(path); total += n
    return m.group(1) + uri + m.group(3)

# src="assets/..." / href="assets/..." / content="assets/..." / url("assets/...")
html = re.sub(r'((?:src|href|content)=")(assets/[^"]+)(")', repl, html)
html = re.sub(r'(url\(")(assets/[^"]+)("\))', repl, html)
# the preload link is pointless once inlined
html = re.sub(r'<link rel="preload" href="data:[^"]+" as="font"[^>]*>\n?', "", html)
# JSON-LD "image": "assets/..." handled above via content=? no — handle plain JSON strings too
html = re.sub(r'("image": ")(assets/[^"]+)(")', repl, html)
html = html.replace("<title>", "<!-- Self-contained build: all images, icons and the heading font are embedded. Generated by build_standalone.py -->\n<title>", 1)
open(OUT, "w", encoding="utf-8").write(html)
print(f"wrote {OUT}  ({os.path.getsize(OUT)/1e6:.2f} MB, embedded assets {total/1e6:.2f} MB raw)")
